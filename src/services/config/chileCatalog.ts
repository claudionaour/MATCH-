export function normalizeRegionName(region?: string | null): string {
  if (!region) return DEFAULT_REGION;
  if (region === 'Región de Los Lagos (Piloto Chiloé)') return 'Región de Los Lagos';
  if (region === 'Región Metropolitana') return 'Región Metropolitana de Santiago';
  const match = REGIONS_CATALOG.find((r) => r.region === region);
  return match ? match.region : DEFAULT_REGION;
}

export function getRegionEntry(region?: string | null) {
  const normalized = normalizeRegionName(region);
  return REGIONS_CATALOG.find((r) => r.region === normalized) || REGIONS_CATALOG.find((r) => r.region === DEFAULT_REGION) || REGIONS_CATALOG[0];
}

